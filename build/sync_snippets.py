"""Copy the Julia snippet sections from snippets/*.jl into the matching notebooks.

The notebook runs Python in the browser, so it cannot run Julia; it shows the Julia
versions as text behind a "Show Julia equivalents" switch. Each notebook holds them in a
generated block between the BEGIN/END JULIA SNIPPETS markers, rewritten here, so the
snippet files stay the single source. build_all.py runs this step, and CI fails if the
committed notebooks differ from what it writes.

Usage:  python build/sync_snippets.py
"""
import sys
from pathlib import Path

# Make the script runnable from any working directory, and under PYTHONSAFEPATH.
sys.path.insert(0, str(Path(__file__).resolve().parent))

from common import NOTEBOOKS_DIR, ROOT, entry_snippets, load_entries

BEGIN = "    # BEGIN JULIA SNIPPETS"
END = "    # END JULIA SNIPPETS"


def block(snippets):
    lines = [BEGIN + " (generated by build/sync_snippets.py from snippets/; do not edit)",
             "    julia_snippets = {"]
    lines += [f"        {name!r}: ({title!r}, {code['jl']!r})," for name, title, code in snippets]
    lines += ["    }", END]
    return "\n".join(lines)


def sync(nb, snippets):
    text = nb.read_text()
    if BEGIN not in text:
        raise ValueError(f"{nb.relative_to(ROOT)} has snippet files but no {BEGIN.strip()} block")
    start, stop = text.index(BEGIN), text.index(END) + len(END)
    new = text[:start] + block(snippets) + text[stop:]
    if new != text:
        nb.write_text(new)
    return new != text


def main():
    done = []
    for meta in load_entries():
        snippets = entry_snippets(meta)
        nb = NOTEBOOKS_DIR / f"{Path(meta['_path']).stem}.py"
        if snippets and nb.exists():
            changed = sync(nb, snippets)
            done.append(f"{nb.name} ({len(snippets)} snippets{', updated' if changed else ''})")
    print("synced Julia snippets into " + (", ".join(done) if done else "no notebooks"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
