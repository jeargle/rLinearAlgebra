@app.cell(hide_code=True)
def _(mo):
    mo.md(r"""
    ### Vibration: $K\varphi = \lambda M \varphi$

    With no load, look for motions in which every joint oscillates in step,
    $u(t) = \varphi \cos \omega t$. Substituting into $M\ddot u + K u = 0$ gives the generalized
    eigenproblem $K\varphi = \lambda M\varphi$ with $\lambda = \omega^2$; the natural frequency
    in hertz is $\omega / 2\pi$.

    **The mass matrix.** A bar of mass $m$ contributes, in each direction, the *consistent*
    mass matrix

    $$\frac{m}{6}\begin{pmatrix}
    2 & 1 \\
    1 & 2
    \end{pmatrix},$$

    which comes from assuming the bar moves linearly between its two ends (the same assumption
    behind its stiffness). The deck's mass is lumped at the bottom joints, in both directions.
    $M$ is symmetric positive definite.

    **Solving it.** Factor $M = L_M L_M^T$ (Cholesky again). With $y = L_M^T \varphi$, the
    problem becomes an ordinary symmetric eigenproblem, $C y = \lambda y$ with
    $C = L_M^{-1} K L_M^{-T}$, whose eigenvectors are orthonormal. Mapped back, the mode shapes
    are **M-orthonormal**: $\varphi_i^T M \varphi_j$ is 1 for $i = j$ and 0 otherwise.
    """)
    return


@app.cell
def _(K_br, K_ff, bars_br, bot_br, dofs, free_br, m_bar, m_deck, n_panels, nodes_br, np, panel):
    def assemble_mass(nodes, bars, m_bar):
        """Consistent mass matrix of the bars: (m / 6) [2 1; 1 2] in each direction."""
        M = np.zeros((2 * len(nodes), 2 * len(nodes)))
        for b, (i, j) in enumerate(bars):
            M[np.ix_(dofs(i, j), dofs(i, j))] += m_bar[b] / 6 * np.kron([[2, 1], [1, 2]], np.eye(2))
        return M

    M_br = assemble_mass(nodes_br, bars_br, m_bar)
    deck_dofs = np.array([[2 * bot_br[k], 2 * bot_br[k] + 1] for k in range(n_panels + 1)])
    deck_mass = m_deck * panel * np.array([0.5 if k in (0, n_panels) else 1.0 for k in range(n_panels + 1)])
    M_br[deck_dofs, deck_dofs] += deck_mass[:, None]   # deck mass lumped at the bottom joints, x and y
    M_ff = M_br[np.ix_(free_br, free_br)]
    L_M = np.linalg.cholesky(M_ff)                # M = L_M L_Mᵀ
    Li_M = np.linalg.inv(L_M)
    C_br = Li_M @ K_ff @ Li_M.T                   # K φ = λ M φ  becomes  C y = λ y,  φ = L_M⁻ᵀ y
    lam_br, y_br = np.linalg.eigh(C_br)
    phi_br = Li_M.T @ y_br
    freq_hz = np.sqrt(lam_br) / (2 * np.pi)
    assert np.all(lam_br > 0) and np.all(np.diff(lam_br) >= 0)
    assert np.allclose(phi_br.T @ M_ff @ phi_br, np.eye(len(free_br)), atol=1e-9)
    assert np.allclose(K_ff @ phi_br, M_ff @ phi_br * lam_br, rtol=1e-8, atol=1e-6 * lam_br.max())
    assert 1.0 < freq_hz[0] < 3.0
    m_orth_err = np.abs(phi_br.T @ M_ff @ phi_br - np.eye(len(free_br))).max()
    return M_br, M_ff, freq_hz, lam_br, m_orth_err, phi_br


