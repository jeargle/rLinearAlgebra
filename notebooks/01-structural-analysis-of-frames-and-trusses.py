def _(mo):
    mo.md(r"""
    ## Notes

    - **Solve, don't invert.** Both the static solve and the eigenproblem use a Cholesky factor
      and triangular solves. Here the matrices are small enough to store densely; at industrial
      size (10⁶–10⁸ DOFs) the same steps run on sparse matrices, with a fill-reducing ordering
      before the factorization.
    - **Only the lowest modes are wanted.** This notebook finds all 45 eigenpairs, which is fine
      at this size. Large models use Lanczos with shift-and-invert, which factors
      $K - \sigma M$ once and returns the few dozen eigenvalues nearest the shift $\sigma$.
    - **Pin-jointed bars only.** A truss bar carries only axial force. Frames with rigid joints
      add a rotation at each joint and bending stiffness, so $K$ mixes N/m with N·m/rad entries,
      but assembly, supports, the solve and the eigenproblem are unchanged.
    """)
    return


