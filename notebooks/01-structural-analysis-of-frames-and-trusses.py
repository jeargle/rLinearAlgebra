    mo.md(r"""
    # Structural analysis: will the bridge hold, and at what frequency does it ring?

    Every bar of a truss behaves like a stiff spring. Writing "the forces balance" at every joint
    gives one linear equation per degree of freedom (DOF), and collecting them gives

    $$K\,u = f,$$

    where $u$ holds the unknown joint displacements, $f$ the known applied loads, and the
    stiffness matrix $K$ holds the spring constants of the bars, arranged by which joints they
    connect. With no load, the same $K$ together with a mass matrix $M$ decides how the
    structure vibrates: $K\varphi = \lambda M \varphi$ with $\lambda = \omega^2$.

    This notebook works the problem twice: first a **three-bar truss** you can check by hand,
    then a **72 m Pratt truss bridge** with 45 bars, solved by Cholesky factorization, with its
    natural frequencies and mode shapes.
    """)
    return


