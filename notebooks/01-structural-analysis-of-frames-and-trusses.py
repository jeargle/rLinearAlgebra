@app.cell
def _(K_br, M_br, bot_br, free_br, n_panels, np, phi_br):
    def full_mode(k):
        """Mode k as a displacement of all DOFs, supported ones included (zero there)."""
        v = np.zeros(K_br.shape[0])
        v[free_br] = phi_br[:, k]
        return v

    def describe_mode(v):
        """Which direction carries the motion, and how many half-waves the deck makes."""
        energy = v * (M_br @ v)                   # M has no x–y coupling, so this splits cleanly
        share_y = energy[1::2].sum() / energy.sum()
        deck = np.array([v[2 * bot_br[k] + 1] for k in range(n_panels + 1)])
        deck = deck[np.abs(deck) > 1e-3 * np.abs(deck).max()]
        waves = 1 + int(np.count_nonzero(np.diff(np.sign(deck))))
        if share_y >= 0.5:
            return f"vertical ({share_y:.0%} of kinetic energy); deck in {waves} half-wave(s)"
        return f"horizontal, along the span ({1 - share_y:.0%} of kinetic energy)"
    return describe_mode, full_mode


