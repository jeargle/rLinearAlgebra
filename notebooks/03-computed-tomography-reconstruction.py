@app.cell(hide_code=True)
def _(mo):
    mo.md(r"""
    ### Tikhonov with a smoothness penalty

    Now take the entry's $L$: the differences between each pixel and its right-hand and lower
    neighbours, so $\|L x\|^2$ adds up the squared jumps across the image. Minimizing

    $$\|A x - b\|^2 + \lambda \|L x\|^2
    \quad\Longleftrightarrow\quad (A^T A + \lambda L^T L)\, x = A^T b$$

    prefers images without pixel-to-pixel jitter, which is exactly what the small-$\sigma$ patterns
    look like. A smooth (constant) image costs nothing, so unlike $L = I$ this choice does not
    pull the overall level toward zero. The cell solves it for 15 values of $\lambda$ from
    $10^{-6}$ to 10.
    """)
    return


@app.cell
def _(A_ct, b_meas, n, np, rel_error, sp):
    D1 = sp.diags([-np.ones(n), np.ones(n - 1)], [0, 1], shape=(n - 1, n))   # neighbour diffs
    L_ct = sp.vstack([sp.kron(sp.eye(n), D1), sp.kron(D1, sp.eye(n))])       # across, then down
    AtA = (A_ct.T @ A_ct).toarray()
    LtL = (L_ct.T @ L_ct).toarray()
    Atb = A_ct.T @ b_meas
    lams = np.logspace(-6, 1, 15)              # two steps per decade

    def tikhonov(lam):
        """Minimize ‖A x − b‖² + λ ‖L x‖² via its normal equations."""
        return np.linalg.solve(AtA + lam * LtL, Atb)

    tik_solutions = [tikhonov(lam) for lam in lams]
    tik_err = np.array([rel_error(x) for x in tik_solutions])
    lam_best = lams[np.argmin(tik_err)]
    x_tik = tik_solutions[int(np.argmin(tik_err))]
    tik_resid = np.array([np.linalg.norm(A_ct @ x - b_meas) for x in tik_solutions])
    tik_rough = np.array([np.linalg.norm(L_ct @ x) for x in tik_solutions])
    return lam_best, lams, tik_err, tik_resid, tik_rough, tik_solutions, x_tik


