@app.cell(hide_code=True)
def _(mo):
    mo.md(r"""
    The left plot needs the true image, which a real scan never has. The right plot, the
    **L-curve**, uses only the data: each point is one λ, placed by how badly it fits the
    measurements and how rough it is. Good values of λ tend to sit near the corner, where cutting
    roughness further starts to cost a lot of misfit.

    ### Kaczmarz / ART: one ray at a time

    The algebraic reconstruction technique (ART) never forms $A^T A$. It visits the rays in turn
    and, for ray $i$, moves $x$ the shortest distance that makes that one equation hold exactly:

    $$x \leftarrow x + \frac{b_i - a_i^T x}{\|a_i\|^2}\, a_i ,$$

    where $a_i^T$ is row $i$ of $A$. Each step touches only the few pixels the ray crosses, which is
    why row-action methods suit huge sparse systems. One *sweep* visits every ray once.
    """)
    return


@app.cell
def _(A_ct, b_meas, np, rel_error):
    def art(A, b, sweeps, omega=1.0):
        """Kaczmarz sweeps: project x onto each ray's equation in turn; x after each sweep."""
        A = A.tocsr()
        row_norm2 = np.asarray(A.multiply(A).sum(axis=1)).ravel()
        x = np.zeros(A.shape[1])
        history = []
        for _ in range(sweeps):
            for i in np.flatnonzero(row_norm2):
                lo, hi = A.indptr[i], A.indptr[i + 1]
                cols, a = A.indices[lo:hi], A.data[lo:hi]
                x[cols] += omega * (b[i] - a @ x[cols]) / row_norm2[i] * a
            history.append(x.copy())
        return x, history

    x_art, art_history = art(A_ct, b_meas, sweeps=30)
    art_err = np.array([rel_error(v) for v in art_history])
    assert art_err[0] > art_err[1] > art_err[2] > art_err[4]   # falls quickly at first
    return art_err, art_history, x_art


