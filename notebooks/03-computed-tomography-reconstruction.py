@app.cell
def _(U_ct, Vt_ct, b_ct, b_meas, np, rank_ct, s_ct, x_true):
    def rel_error(x):
        return np.linalg.norm(x - x_true) / np.linalg.norm(x_true)

    coef_ct = U_ct[:, :rank_ct].T @ b_meas / s_ct[:rank_ct]   # each component divided by σ
    x_naive = Vt_ct[:rank_ct].T @ coef_ct
    x_clean = Vt_ct[:rank_ct].T @ (U_ct[:, :rank_ct].T @ b_ct / s_ct[:rank_ct])   # no noise
    err_naive = rel_error(x_naive)
    assert err_naive > 3 * rel_error(x_clean)
    return coef_ct, err_naive, rel_error, x_clean, x_naive


