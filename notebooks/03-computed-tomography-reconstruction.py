@app.cell(hide_code=True)
def _(mo):
    mo.md(r"""
    ## Notes

    - **Never invert $A$.** Even forming $A^T A$, as the Tikhonov cell does, is affordable only at
      toy sizes: at 512 × 512 pixels it would have about 7 × 10¹⁰ entries. Real reconstructions
      use row-action methods like ART, or conjugate gradients on the normal equations, which only
      ever multiply by $A$ and $A^T$.
    - **Filtered backprojection** (FBP), the classical method, is a fast analytic inverse of the
      continuous Radon transform and is not shown here. It needs many evenly spaced angles; the
      iterative methods above cope better with few or irregular views.
    - **The model is approximate.** The Beer–Lambert law above assumes one X-ray energy. Real tubes
      emit a spectrum and low-energy photons are absorbed first (beam hardening), which breaks the
      linearity and causes its own artifacts.
    - **Total variation.** Commercial scanners now often penalize $\|L x\|_1$ instead of
      $\|L x\|^2$. It allows sharp edges where the squared penalty blurs them, at the cost of an
      optimization problem that is no longer linear.
    """)
    return


