@app.cell(hide_code=True)
def _(mo):
    mo.md(r"""
    ### The SVD: which patterns can the rays see?

    Without ray 5 the system could not be solved at all. Add the **checkerboard**
    $(+1, -1, -1, +1)$ to the image: every row and every column contains one $+1$ and one $-1$,
    so rays 1–4 read exactly the same totals. That pattern is in the null space of the first four
    rows. Ray 5 sees it, but only through its 0.2 cm chord in $P$.

    The singular value decomposition $A = U \Sigma V^T$ makes this precise. The columns $v_k$ of
    $V$ are image patterns, the columns $u_k$ of $U$ are the measurement patterns they produce, and
    $A v_k = \sigma_k u_k$: the singular value $\sigma_k$ is how strongly pattern $v_k$ shows up in
    the data.
    """)
