@app.cell(hide_code=True)
def _(mo):
    mo.md(r"""
    ### One ray first: why the logarithm makes it linear

    Inside a uniform material the beam obeys the Beer–Lambert law, the first-order ODE
    $dI/ds = -\mu I$. Its solution is the familiar exponential fall-off

    $$I = I_0\, e^{-\mu s}$$

    after a path of length $s$. Follow ray 2. It crosses $R$ for 1 cm, so $e^{-0.2 \cdot 1}$ of the
    photons survive; the survivors then cross $S$ for 1 cm, and $e^{-0.5 \cdot 1}$ of *those*
    survive. Surviving fractions **multiply**:

    $$\frac{I_2}{I_0} = e^{-0.2 \cdot 1}\, e^{-0.5 \cdot 1} = e^{-(0.2 \cdot 1 + 0.5 \cdot 1)} = e^{-0.7} \approx 0.497.$$

    Taking $b_2 = -\ln(I_2 / I_0)$ turns the product back into a sum,

    $$b_2 = 1 \cdot \mu_R + 1 \cdot \mu_S = 0.7,$$

    which is linear in the unknowns, with the path lengths as coefficients. The raw detector
    reading is not linear in $\mu$; its logarithm is.
    """)
    return


@app.cell
def _(A_toy, b_toy, np, x_toy):
    I0 = 1.0e5                                 # photons sent along each ray
    I_toy = I0 * np.exp(-b_toy)                # what the detectors count (no noise yet)
    assert np.isclose(I_toy[1] / I0, np.exp(-0.2) * np.exp(-0.5))   # fractions multiply
    assert np.allclose(-np.log(I_toy / I0), A_toy @ x_toy)           # logs add: linear in μ
    return I0, I_toy


