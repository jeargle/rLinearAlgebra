@app.cell(hide_code=True)
def _(mo):
    mo.md(r"""
    ### The same patterns from the covariance matrix

    The familiar route forms the spatial covariance $C = X X^{\mathsf T}/(t-1)$, an $s \times s$
    matrix, and diagonalizes it. Substituting the SVD shows why the two routes agree:

    $$C = \frac{1}{t-1} U \Sigma V^{\mathsf T} V \Sigma U^{\mathsf T}
        = U \, \frac{\Sigma^2}{t-1} \, U^{\mathsf T},$$

    so the eigenvectors of $C$ are the EOFs and its eigenvalues are $\lambda_i = \sigma_i^2/(t-1)$.
    The SVD is preferred in practice: it never forms $C$ (which squares the condition number), and
    when $s \gg t$ it never builds an $s \times s$ matrix at all.
    """)
    return


