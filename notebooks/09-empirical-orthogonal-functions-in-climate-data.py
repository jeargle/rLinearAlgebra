    mo.md(r"""
    # Empirical orthogonal functions: the dominant patterns in a temperature record

    A climate record is a stack of maps, one per month. Neighbouring grid points rise and fall
    together, so the record is far more redundant than its size suggests. Empirical orthogonal
    function (EOF) analysis finds the few spatial patterns that, each multiplied by its own time
    series, rebuild the record as accurately as possible.

    Climatologists usually state it as an eigenproblem: the EOFs are the eigenvectors of the
    spatial covariance matrix, $C\,u_i = \lambda_i u_i$, and the principal-component (PC) series is
    the projection of each month's map onto a pattern. The linear-algebra statement is the
    singular value decomposition of the anomaly matrix,

    $$X = U \Sigma V^{\mathsf T} = \sum_i \sigma_i\, u_i v_i^{\mathsf T},$$

    over the real numbers $\mathbb{R}$. Each column of $X$ (one month's map) lives in
    $\mathbb{R}^s$, with $s$ grid points; each row (one grid point's history) lives in
    $\mathbb{R}^t$, with $t$ months. The EOFs $u_i$ are an orthonormal basis of the part of
    $\mathbb{R}^s$ the maps occupy, and the $v_i$ are their partners in $\mathbb{R}^t$.

    **Known:** the temperatures $T_{gk}$ and the grid (hence the area weights $W$).
    **Unknown:** the patterns $U$, their strengths $\Sigma$ and the time series $V$.

    This notebook works the problem twice: first a **4-site, 6-month toy** you can check by hand,
    then a **synthetic Pacific sea-surface temperature field with two planted modes**, where we know
    the right answer and can watch the method find it, and then fail to separate it.
    """)
    return


