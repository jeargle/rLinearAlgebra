@app.cell
def _(a_enso, a_trend, amp_enso, noise_sst, np, p_enso, p_trend, pattern_corr, svds, t_sst, w_sst):
    def leading_modes(r):
        """EOFs 1-2 and eigenvalues 1-3 of the field with planted variance ratio r (truncated SVD)."""
        amp = amp_enso * np.sqrt(r) * np.linalg.norm(w_sst * p_enso) / np.linalg.norm(w_sst * p_trend)
        WX = w_sst[:, None] * (amp_enso * np.outer(p_enso, a_enso) + amp * np.outer(p_trend, a_trend)
                               + noise_sst)
        u, sv, _ = svds(WX, k=3, random_state=0)
        order = np.argsort(sv)[::-1]
        u = u[:, order] * np.where(u[:, order].T @ (w_sst * p_enso) < 0, -1, 1)  # warm east > 0
        return u, sv[order]**2 / (t_sst - 1)

    def mix_scores(r):
        """For ratio r: cosine of EOF 1 with ENSO, of EOF 2 with warming, and North's gap test."""
        u, lam = leading_modes(r)
        enso_r = max(pattern_corr(u[:, 0], p_enso, w_sst), pattern_corr(u[:, 1], p_enso, w_sst))
        trend_r = max(pattern_corr(u[:, 0], p_trend, w_sst), pattern_corr(u[:, 1], p_trend, w_sst))
        return enso_r, trend_r, (lam[0] - lam[1]) / (lam[0] * np.sqrt(2 / t_sst))

    mix_grid = np.round(np.arange(0.05, 2.001, 0.05), 2)
    mix_curve = np.array([mix_scores(r) for r in mix_grid])
    return leading_modes, mix_curve, mix_grid


