@app.cell(hide_code=True)
def _(mo):
    mo.md(r"""
    ### North's rule of thumb

    The eigenvalues $\lambda_i = \sigma_i^2/(t-1)$ are estimates from a finite record. North et al.
    (1982) give their sampling error as roughly $\delta\lambda_i \approx \lambda_i\sqrt{2/N}$, with $N$
    the number of independent samples. If the gap to the next eigenvalue is smaller than
    $\delta\lambda_i$, the two EOFs are not separately determined: any rotation of the pair fits the
    data about as well. Using $N = t$ treats every month as independent, which is optimistic for
    autocorrelated data such as ENSO, so the true error bars are wider.
    """)
    return


@app.cell
def _(S_sst, frac_sst, np, t_sst):
    lam_sst = S_sst**2 / (t_sst - 1)                     # eigenvalues of the weighted covariance
    dlam_sst = lam_sst * np.sqrt(2 / t_sst)              # sampling error, if months were independent
    separated = lam_sst[:-1] - lam_sst[1:] > dlam_sst[:-1]
    assert separated[0] and separated[1]                 # modes 1 and 2 stand clear of their neighbours
    assert frac_sst[2] < 0.01                            # mode 3 onward is noise
    return dlam_sst, lam_sst


