@app.cell(hide_code=True)
def _(mo, s_sst, t_sst):
    mo.md(rf"""
    ### Truncated SVD

    $W X$ is ${s_sst} \times {t_sst}$. One component first: the PC value of pattern $i$ in month
    $k$ is the projection of that month's weighted map onto the pattern,
    $a_i(k) = \sum_g u_{{gi}}\,(W x)_{{gk}} = u_i^{{\mathsf T}} (W x_k)$. Stacking all months in a row,
    $a_i^{{\mathsf T}} = u_i^{{\mathsf T}} W X = \sigma_i v_i^{{\mathsf T}}$, which is the SVD read
    one row at a time. We keep $q = 2$ modes. (At full scale one would compute only the leading
    singular triplets, with a randomized or Lanczos method; here the full SVD takes a fraction of a
    second, and it gives every singular value for the scree plot.)
    """)
    return


@app.cell
def _(WX_sst, np, p_enso, p_trend, w_sst):
    U_sst, S_sst, Vt_sst = np.linalg.svd(WX_sst, full_matrices=False)
    q = 2                                                # modes retained
    sign_sst = np.sign(np.array([U_sst[:, 0] @ (w_sst * p_enso), U_sst[:, 1] @ (w_sst * p_trend)]))
    U_sst[:, :q] *= sign_sst                             # the SVD fixes each pattern only up to sign
    Vt_sst[:q] *= sign_sst[:, None]
    eof_maps = U_sst[:, :q] / w_sst[:, None]             # undo the weighting before plotting
    pc_sst = Vt_sst[:q].T * S_sst[:q]                    # PC time series a_i = sigma_i v_i
    frac_sst = S_sst**2 / np.sum(S_sst**2)
    WX_q = (U_sst[:, :q] * S_sst[:q]) @ Vt_sst[:q]
    err_q = np.linalg.norm(WX_sst - WX_q)
    assert np.isclose(err_q**2, np.sum(S_sst[q:]**2))   # Eckart-Young: error^2 = discarded sigma^2
    return S_sst, U_sst, eof_maps, err_q, frac_sst, pc_sst, q


