@app.cell(hide_code=True)
def _(mo):
    mo.md(r"""
    ## The pitfall: optimal is not the same as physical

    EOFs are forced to be orthogonal; physical patterns are not. When two modes carry similar
    variance, the leading eigenvalues come close together and the SVD is free to return any
    orthogonal pair in their shared plane. It picks the pair that maximizes variance in the first
    pattern, which for two overlapping patterns of equal strength is their **sum**: a blend of two
    unrelated mechanisms. The cell below recomputes the analysis with the warming mode as strong as
    the ENSO mode, using the same time series and noise.
    """)
    return


@app.cell
def _(a_enso, a_trend, amp_enso, corr_enso, noise_sst, np, p_enso, p_trend, pattern_corr, w_sst):
    amp_eq = amp_enso * np.linalg.norm(w_sst * p_enso) / np.linalg.norm(w_sst * p_trend)  # ratio = 1
    X_eq = amp_enso * np.outer(p_enso, a_enso) + amp_eq * np.outer(p_trend, a_trend) + noise_sst
    U_eq, S_eq, _ = np.linalg.svd(w_sst[:, None] * X_eq, full_matrices=False)
    corr_eq = pattern_corr(U_eq[:, 0], p_enso, w_sst)
    blend = p_enso / np.linalg.norm(w_sst * p_enso) + p_trend / np.linalg.norm(w_sst * p_trend)
    corr_blend = pattern_corr(U_eq[:, 0], blend, w_sst)
    assert corr_eq < corr_enso and corr_blend > corr_eq  # EOF 1 is now a mixture of both mechanisms
    return corr_blend, corr_eq


