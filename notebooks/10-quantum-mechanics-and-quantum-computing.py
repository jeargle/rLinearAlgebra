@app.cell(hide_code=True)
def _(mo):
    mo.md(r"""
    ### Degeneracy, and a real basis for each pair

    Two levels are **degenerate**: $k$ and $6 - k$ have the same $\cos$, so $\varphi_1$ and
    $\varphi_5$ share the energy $\alpha + \beta$, and $\varphi_2$ and $\varphi_4$ share
    $\alpha - \beta$. A degenerate level is not one vector but a plane: every combination
    $a\varphi_1 + b\varphi_5$ is an eigenvector with the same energy. Asking for "the" eigenvector
    has no answer; only the plane is determined.

    That freedom lets us pick a real basis. Since $H$ is real, $\varphi_5 = \overline{\varphi_1}$,
    and the sum and difference of a complex vector and its conjugate are real:

    $$\frac{\varphi_k + \varphi_{6-k}}{\sqrt 2} = \sqrt{\tfrac{2}{6}}\,\cos\frac{2\pi jk}{6},
    \qquad
    \frac{\varphi_k - \varphi_{6-k}}{i\sqrt 2} = \sqrt{\tfrac{2}{6}}\,\sin\frac{2\pi jk}{6}.$$

    These are the orbitals drawn in chemistry books. The complex pair and the real pair span the
    same plane; the complex ones are eigenvectors of the rotation $R$ too, and the real ones are
    not. A numerical eigensolver makes its own choice inside each plane, so the test that it agrees
    with us compares the **projector** onto the plane, $P = V V^{\mathsf T}$ for any orthonormal
    basis $V$ of it, not the vectors.
    """)
    return


@app.cell
def _(H_benz, alpha, beta, j_site, np):
    _c = lambda k: np.sqrt(2 / 6) * np.cos(2 * np.pi * k * j_site / 6)
    _s = lambda k: np.sqrt(2 / 6) * np.sin(2 * np.pi * k * j_site / 6)
    Q_benz = np.column_stack([np.ones(6) / np.sqrt(6), _c(1), _s(1),
                              _c(2), _s(2), (-1.0) ** j_site / np.sqrt(6)])
    E_real = alpha + beta * np.array([2, 1, 1, -1, -1, -2])
    assert np.allclose(Q_benz.T @ Q_benz, np.eye(6))                  # orthonormal, real
    assert np.allclose(Q_benz.T @ H_benz @ Q_benz, np.diag(E_real))   # and it diagonalizes H
    E_eigh, V_eigh = np.linalg.eigh(H_benz)        # LAPACK's own choice inside each degenerate pair
    assert np.allclose(E_eigh, E_real)
    P_real = Q_benz[:, 1:3] @ Q_benz[:, 1:3].T     # projector onto the α + β level
    P_eigh = V_eigh[:, 1:3] @ V_eigh[:, 1:3].T
    assert np.allclose(P_real, P_eigh)             # the level is the same plane either way
    return E_eigh, E_real, Q_benz, V_eigh


