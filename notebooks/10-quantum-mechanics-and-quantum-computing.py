@app.cell(hide_code=True)
def _(mo):
    mo.md(r"""
    ### The familiar formula: the secular determinant

    Chemistry texts find the energies from the *secular determinant*
    $\det(H - EI) = 0$. Dividing every row by $\beta$ and writing $x = (\alpha - E)/\beta$ gives
    $\det(xI + A^{G}) = 0$. So $-x$ runs over the eigenvalues $\mu$ of the adjacency matrix,
    and

    $$E = \alpha + \beta\mu.$$

    $H$ and $A^{G}$ have the same eigenvectors. The chemistry is in two numbers; the rest is graph
    theory.

    ### Diagonalizing by symmetry

    Take one component of $H\varphi = E\varphi$. Row $j$ says

    $$\alpha\,\varphi_j + \beta\,(\varphi_{j-1} + \varphi_{j+1}) = E\,\varphi_j,
    \qquad j = 0, \dots, 5,\ \text{indices mod } 6.$$

    Every row has the same form, because rotating the ring by $60^\circ$ does not change the
    molecule. So try a vector that rotation only multiplies by a constant:
    $\varphi_j = \omega^{jk}$ with $\omega = e^{2\pi i/6}$, for one fixed $k$. Dividing row $j$ by
    $\omega^{jk}$ leaves

    $$\alpha + \beta\,(\omega^{-k} + \omega^{k}) = E
    \quad\Longrightarrow\quad E_k = \alpha + 2\beta\cos\frac{2\pi k}{6},$$

    the same for every row, so $\varphi$ really is an eigenvector. The six values $k = 0, \dots, 5$
    give six orthogonal vectors. Normalized by $1/\sqrt 6$ they are the columns of the
    $6 \times 6$ **discrete Fourier matrix** $F$. In matrix form: the cyclic shift $R$ (move every
    entry one place round the ring) has the Fourier vectors as eigenvectors, and
    $A^{G} = R + R^{\mathsf T}$, so they diagonalize $A^{G}$ too.
    """)
    return


@app.cell
def _(H_benz, alpha, beta, np):
    j_site = np.arange(6)
    F_benz = np.exp(2j * np.pi * np.outer(j_site, j_site) / 6) / np.sqrt(6)  # column k: φ_k
    mu_benz = 2 * np.cos(2 * np.pi * j_site / 6)       # adjacency eigenvalues 2, 1, -1, -2, -1, 1
    E_benz = alpha + beta * mu_benz
    assert np.allclose(F_benz.conj().T @ F_benz, np.eye(6))     # F is unitary
    assert np.allclose(H_benz @ F_benz, F_benz * E_benz)        # H φ_k = E_k φ_k for every k
    assert np.allclose(np.sort(E_benz), alpha + beta * np.array([2, 1, 1, -1, -1, -2]))
    return E_benz, j_site, mu_benz


